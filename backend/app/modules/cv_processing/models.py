import uuid
from typing import Optional, List, Dict, Any, TYPE_CHECKING
from sqlalchemy import String, Text, Numeric, ForeignKey
from sqlalchemy.dialects.postgresql import UUID, JSONB
from sqlalchemy.orm import Mapped, mapped_column, relationship
from pgvector.sqlalchemy import Vector

from app.core.base_model import Base, UUIDPrimaryKeyMixin, TimestampMixin

if TYPE_CHECKING:
    from app.modules.users.models import User
    from app.modules.matching.models import JobMatch


class CvProfile(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """
    Extracted candidate profile parsed from an uploaded PDF.
    Holds structured data, verbatim source quotes, and a 768-dim vector embedding.
    """
    __tablename__ = "cv_profiles"

    user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        unique=True,
        nullable=False,
        index=True,
    )

    # Raw extracted text from PDF (used for citation verification)
    raw_text: Mapped[str] = mapped_column(Text, nullable=False)

    # High-level summary & target role
    target_role: Mapped[Optional[str]] = mapped_column(String(150), nullable=True)
    years_of_experience: Mapped[Optional[float]] = mapped_column(Numeric(4, 1), nullable=True)

    # Semi-structured JSON fields with verbatim citations
    # Example structured_data: {"contact": {"phone": "...", "linkedin": "..."}, "education": [...]}
    structured_data: Mapped[Dict[str, Any]] = mapped_column(JSONB, default=dict, nullable=False)
    
    # Example work_experiences: [{"role": "Android Dev", "company": "...", "start": "...", "quote": "..."}]
    work_experiences: Mapped[List[Dict[str, Any]]] = mapped_column(JSONB, default=list, nullable=False)

    # Example skills: [{"name": "Kotlin", "category": "Languages", "years": 4.0, "quote": "..."}]
    skills: Mapped[List[Dict[str, Any]]] = mapped_column(JSONB, default=list, nullable=False)

    # 768-dimensional embedding generated by Gemini text-embedding-004
    embedding: Mapped[Optional[List[float]]] = mapped_column(Vector(768), nullable=True)

    # Relationships
    user: Mapped["User"] = relationship("User", back_populates="cv_profile")
    job_matches: Mapped[List["JobMatch"]] = relationship(
        "JobMatch", back_populates="cv_profile", cascade="all, delete-orphan"
    )

    def __repr__(self) -> str:
        return f"<CvProfile(id={self.id}, user_id={self.user_id}, target_role='{self.target_role}')>"
